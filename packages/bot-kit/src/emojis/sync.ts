import * as crypto from 'crypto';
import { parse } from 'path';

import { Glob } from 'bun';
import { type ApplicationEmoji, type Client, type Collection, Snowflake } from 'discord.js';

import { type DiscoverableSearch, normalizeSearch } from '../util/autoDiscover.js';
import { type MaybeReadonlyArray, resolveMaybeReadonlyArray } from '../util/maybeReadonlyArray.js';
import { toPascalCase } from '../util/toPascalCase.js';

interface Options {
  paths: MaybeReadonlyArray<Required<DiscoverableSearch>>;
  getHashes: (appId: string) => Promise<Record<string, string>>;
  saveHashes: (appId: string, hashes: Record<string, string>) => Promise<void>;

  formatDiscordName?: (fileName: string) => string;
  enum?: EnumOptions;
}

interface EnumOptions {
  path: string;
  name?: string;
  formatEnumKey?: (discordName: string) => string;
}

export async function executeApplicationEmojiSync(
  client: Client<true>,
  options: Options,
): Promise<void> {
  const buffers = new Map<string, Uint8Array<ArrayBuffer>>();
  const hashes: Record<string, string> = {};

  const paths = resolveMaybeReadonlyArray(options.paths);
  for (const search of paths) {
    const { root, pattern } = normalizeSearch(search);
    const glob = new Glob(pattern);

    const filePaths = await Array.fromAsync(glob.scan({ cwd: root, absolute: true }));
    await Promise.all(
      filePaths.map(async (path) => {
        const fileName = parse(path).name;
        const discordName = options.formatDiscordName?.(fileName) ?? fileName;
        const buffer = await Bun.file(path).bytes();
        const hash = crypto.createHash('md5').update(buffer).digest('hex');
        buffers.set(discordName, buffer);
        hashes[discordName] = hash;
      }),
    );
  }

  let appEmojis: Collection<Snowflake, ApplicationEmoji> | undefined;
  let stateChanged = false;

  const previousHashes = await options.getHashes(client.application.id);
  await Promise.all(
    Object.keys(previousHashes).map(async (name) => {
      if (!buffers.has(name)) {
        console.log(`Removed locally: Deleting '${name}' from Discord`);
        appEmojis ??= await client.application.emojis.fetch();

        const existing = appEmojis.find((e) => e.name === name);
        if (existing) {
          await existing.delete();
        }
        stateChanged = true;
      }
    }),
  );

  await Promise.all(
    Object.entries(hashes).map(async ([name, hash]) => {
      if (previousHashes[name] === hash) {
        return;
      }

      console.log(
        previousHashes[name] == null
          ? `Added locally: Uploading '${name}' to Discord`
          : `Updated locally: Updating '${name}' on Discord`,
      );
      appEmojis ??= await client.application.emojis.fetch();

      const existing = appEmojis.find((e) => e.name === name);
      if (existing) {
        await existing.delete();
      }

      await client.application.emojis.create({
        name,
        attachment: Buffer.from(buffers.get(name)!),
      });
      stateChanged = true;
    }),
  );

  if (stateChanged) {
    await options.saveHashes(client.application.id, hashes);
  } else {
    console.log('Already up to date.');
  }

  if (options.enum) {
    const fetched = await client.application.emojis.fetch();
    await generateEnumFile(
      fetched.map((e) => e.name),
      options.enum,
    );
    return;
  }
}

async function generateEnumFile(
  names: readonly string[],
  { path, name, formatEnumKey = toPascalCase }: EnumOptions,
): Promise<void> {
  const sorted = names.toSorted();

  let fileContent = `
// AUTO-GENERATED BY '@raspberryvarg/bot-kit'.
// DO NOT EDIT THIS FILE MANUALLY.
`.trimStart();

  fileContent += `export enum ${name || 'Emojis'} {\n`;
  for (const key of sorted) {
    fileContent += `  ${formatEnumKey(key)} = '${key}',\n`;
  }
  fileContent += '}\n';

  await Bun.write(path, fileContent);
  console.log(`Updated enum file at '${path}' with ${sorted.length} emojis.`);
}
